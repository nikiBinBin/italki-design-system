import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

/* Generates the Icon Library manifest from the Assets/Icons directory.

   The Catalog is a static page and cannot list a directory, so it used to
   carry a hand-maintained iconAssets array — which drifted to 88 icons short
   of the disk before anyone noticed. This script IS the listing; the page
   loads its output, and validate-contracts.mjs fails when the output is stale,
   so an icon dropped into Assets/Icons cannot silently miss the library. */

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, "..", "..");

/* Brand and credential marks the library shows first. */
const PINNED = [
  "Assets/Icons/logo-italki-plus.svg",
  "Assets/Icons/Plustag.svg",
  "Assets/Icons/teacher-professional.svg",
  "Assets/Icons/teacher-community.svg",
];

/* Curated exclusions, carried over from the page's old inline list: each is
   pixel-identical to an asset the library already publishes, so listing it
   would show the same glyph twice. back.svg duplicates arrow-left.svg;
   arrow-right-1.svg and arrow-up-1.svg are stray thin-stroke exports of the
   removed backup set. The files stay on disk for anything pointing at them. */
const EXCLUDED = new Set([
  "Assets/Icons/back.svg",
  "Assets/Icons/arrow-right-1.svg",
  "Assets/Icons/arrow-up-1.svg",
]);

const walk = (dir) =>
  fs.readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) return walk(full);
    return entry.name.endsWith(".svg") ? [path.relative(root, full)] : [];
  });

const all = walk(path.join(root, "Assets", "Icons")).sort();
for (const pinned of PINNED) {
  if (!all.includes(pinned)) throw new Error(`Pinned icon missing on disk: ${pinned}`);
}
const rest = all.filter((asset) => !PINNED.includes(asset) && !EXCLUDED.has(asset));
const manifest = [...PINNED, ...rest];

const body = manifest.map((asset) => `  ${JSON.stringify(asset)}`).join(",\n");
fs.writeFileSync(
  path.join(root, "catalog-runtime", "icon-manifest.js"),
  `// Generated by maintenance/scripts/build-icon-manifest.mjs — do not edit.\n` +
    `// Lists Assets/Icons for the Catalog's Icon Library (${manifest.length} of ${all.length} on disk;\n` +
    `// ${EXCLUDED.size} duplicates excluded by the script's curated list).\n` +
    `window.ITalkiIconManifest = [\n${body}\n];\n`,
);
console.log(`icon-manifest.js: ${manifest.length} icons (${all.length} on disk, ${EXCLUDED.size} excluded)`);
