import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

/* Generates the Icon Library manifest from the Assets/Icons directory.

   The Catalog is a static page and cannot list a directory, so it used to
   carry a hand-maintained iconAssets array — which drifted to 88 icons short
   of the disk before anyone noticed. This script IS the listing; the page
   loads its output, and validate-contracts.mjs fails when the output is stale,
   so an icon dropped into Assets/Icons cannot silently miss the library. */

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, "..", "..");

/* Brand and credential marks the library shows first. */
const PINNED = [
  "Assets/Icons/logo-italki-plus.svg",
  "Assets/Icons/Plustag.svg",
  "Assets/Icons/teacher-professional.svg",
  "Assets/Icons/teacher-community.svg",
];

/* Curated exclusions, carried over from the page's old inline list: each is
   pixel-identical to an asset the library already publishes, so listing it
   would show the same glyph twice. back.svg duplicates arrow-left.svg;
   arrow-right-1.svg and arrow-up-1.svg are stray thin-stroke exports of the
   removed backup set. The files stay on disk for anything pointing at them.

   The second group is the other half of the adopted set's 20 name collisions:
   these five are the same drawing at both paths, so the Catalog showed one
   glyph on both boards — once as italki's own and once as a general one — and
   it read as the general set leaking into the library. It is the reverse. The
   library's copy is the published one because that is the path the contracts
   name: number-stepper's plus and minus, List's marker, Sidebar's section
   arrow, Footer's YouTube, Breadcrumb's home. The adopted twin is dropped from
   the manifest, not from disk, and bare-name resolution is unaffected —
   resolveIcon already prefers the library's own over anything under ui/. */
const EXCLUDED = new Set([
  "Assets/Icons/back.svg",
  "Assets/Icons/arrow-right-1.svg",
  "Assets/Icons/arrow-up-1.svg",
  "Assets/Icons/ui/plus-circle.svg",
  "Assets/Icons/ui/minus-circle.svg",
  "Assets/Icons/ui/chevron-right.svg",
  "Assets/Icons/ui/home-01.svg",
  "Assets/Icons/ui/youtube.svg",
]);

/* Directories that sit under Assets/Icons without being part of the library.
   The manifest is what `approvedAsset()` checks, so anything this walk reaches
   becomes an icon a component is allowed to render and an entry on the Icon
   foundation card. A 1,171-file general-purpose set arrived in Assets/Icons/
   backup/ on 2026-08-17 and the count went 362 → 1,533 in one build, which is
   how the folder came to be skipped: publishing an icon set is a decision, and
   walking a folder is not how it should get taken.

   It was then taken — the set is adopted, and lives at Assets/Icons/ui/ rather
   than in the library root because 20 of its files carry a name the library
   already uses and 15 of those are a different drawing. Directory placement
   alone does not settle which one a bare `icon: "check"` reaches; resolveIcon
   in the runtime does, by preferring the library's own. `backup` stays listed
   so the next set dropped there is parked rather than published. */
const UNPUBLISHED_DIRS = new Set(["backup"]);

const walk = (dir) =>
  fs.readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) return UNPUBLISHED_DIRS.has(entry.name) ? [] : walk(full);
    return entry.name.endsWith(".svg") ? [path.relative(root, full)] : [];
  });

const all = walk(path.join(root, "Assets", "Icons")).sort();
for (const pinned of PINNED) {
  if (!all.includes(pinned)) throw new Error(`Pinned icon missing on disk: ${pinned}`);
}
const rest = all.filter((asset) => !PINNED.includes(asset) && !EXCLUDED.has(asset));
const manifest = [...PINNED, ...rest];

const body = manifest.map((asset) => `  ${JSON.stringify(asset)}`).join(",\n");
fs.writeFileSync(
  path.join(root, "catalog-runtime", "icon-manifest.js"),
  `// Generated by maintenance/scripts/build-icon-manifest.mjs — do not edit.\n` +
    `// Lists Assets/Icons for the Catalog's Icon Library (${manifest.length} of ${all.length} on disk;\n` +
    `// ${EXCLUDED.size} duplicates excluded by the script's curated list).\n` +
    `window.ITalkiIconManifest = [\n${body}\n];\n`,
);
console.log(`icon-manifest.js: ${manifest.length} icons (${all.length} on disk, ${EXCLUDED.size} excluded)`);
