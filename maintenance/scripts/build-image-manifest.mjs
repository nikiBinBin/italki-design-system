import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

/* Generates the Image resource manifest from the Assets/Images directory.

   Same reason as the icon manifest: the Catalog is a static page and cannot
   list a directory. Until now nothing listed these files at all — the Image
   foundation card documented the two approved crop ratios and stopped there,
   so the only way to learn that `Assets/Images/avatars/teacher-lucia.png`
   exists was to read a template that already used it. An asset nobody can find
   is not a resource, and the ones that were found got reused by copy-paste
   from whichever page happened to reference them.

   Contracts already allow the whole of `Assets/Images/` — see assetRoots in
   contracts.json — so this adds discovery, not permission. validate-contracts
   fails when the output is stale, so an image dropped into the folder cannot
   silently miss the card. */

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, "..", "..");

/* Raster and vector content imagery. `.DS_Store` is the reason this is an
   allow-list rather than a deny-list: Finder writes one into any folder a
   person has opened, and a deny-list grows a new entry every time some other
   tool leaves something behind. */
const EXTENSIONS = new Set([".png", ".jpg", ".jpeg", ".webp", ".svg"]);

const walk = (dir) =>
  fs.readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) return walk(full);
    return EXTENSIONS.has(path.extname(entry.name).toLowerCase()) ? [path.relative(root, full)] : [];
  });

const manifest = walk(path.join(root, "Assets", "Images")).sort();

const body = manifest.map((asset) => `  ${JSON.stringify(asset)}`).join(",\n");
fs.writeFileSync(
  path.join(root, "catalog-runtime", "image-manifest.js"),
  `// Generated by maintenance/scripts/build-image-manifest.mjs — do not edit.\n` +
    `// Lists Assets/Images for the Catalog's Image foundation card (${manifest.length} files).\n` +
    `window.ITalkiImageManifest = [\n${body}\n];\n`,
);
console.log(`image-manifest.js: ${manifest.length} images`);
